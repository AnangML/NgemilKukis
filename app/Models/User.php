<?php

namespace App\Models;

// use Illuminate\Contracts\Auth\MustVerifyEmail;
use Database\Factories\UserFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Hidden;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Relations\HasMany;
use Illuminate\Foundation\Auth\User as Authenticatable;
use Illuminate\Notifications\Notifiable;

#[Fillable([
    'name',
    'email',
    'password',
    'role',
    'phone',
    'google_id',
    'avatar_url',
    'auth_provider',
    'saved_address',
    'saved_city',
    'member_discount_amount',
    'points_balance',
    'phone_verified_at',
])]
#[Hidden(['password', 'remember_token'])]
class User extends Authenticatable
{
    /** @use HasFactory<UserFactory> */
    use HasFactory, Notifiable;

    /**
     * Get the attributes that should be cast.
     *
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'email_verified_at' => 'datetime',
            'phone_verified_at' => 'datetime',
            'password' => 'hashed',
            'member_discount_amount' => 'integer',
            'points_balance' => 'integer',
        ];
    }

    /**
     * Determine if the user has an admin role.
     */
    public function isAdmin(): bool
    {
        return $this->role === 'admin';
    }

    /**
     * Determine if the user has a seller (penjual) role.
     */
    public function isSeller(): bool
    {
        return $this->role === 'seller';
    }

    /**
     * Determine if the user has a customer service role.
     */
    public function isCustomerService(): bool
    {
        return $this->role === 'customer_service';
    }

    /**
     * Determine if the user is an internal staff member (admin, seller, or CS).
     */
    public function isStaff(): bool
    {
        return in_array($this->role, ['admin', 'seller', 'customer_service'], true);
    }

    /**
     * Determine if the user has a customer role.
     */
    public function isCustomer(): bool
    {
        return $this->role === 'customer';
    }

    /**
     * Check if the user can manage site settings and brand identity.
     */
    public function canManageSettings(): bool
    {
        return $this->isAdmin();
    }

    /**
     * Check if the user can manage products catalog and stock.
     */
    public function canManageProducts(): bool
    {
        return in_array($this->role, ['admin', 'seller'], true);
    }

    /**
     * Check if the user can manage orders.
     */
    public function canManageOrders(): bool
    {
        return $this->isStaff();
    }

    /**
     * Check if the user can manage internal staff members.
     */
    public function canManageStaff(): bool
    {
        return $this->isAdmin();
    }

    /**
     * Check if the user can view activity logs.
     */
    public function canViewLogs(): bool
    {
        return $this->isAdmin();
    }

    /**
     * Get human-friendly Indonesian role label.
     */
    public function getRoleLabelAttribute(): string
    {
        return match ($this->role) {
            'admin' => 'Super Admin',
            'seller' => 'Penjual (Toko)',
            'customer_service' => 'Customer Service',
            default => 'Pelanggan',
        };
    }

    /**
     * Get Tailwind CSS classes for role badge.
     */
    public function getRoleBadgeClassesAttribute(): string
    {
        return match ($this->role) {
            'admin' => 'bg-amber-100 text-amber-900 border-amber-300',
            'seller' => 'bg-blue-100 text-blue-900 border-blue-300',
            'customer_service' => 'bg-emerald-100 text-emerald-900 border-emerald-300',
            default => 'bg-stone-100 text-stone-700 border-stone-300',
        };
    }

    /**
     * Activity logs generated by this user.
     *
     * @return HasMany<ActivityLog, $this>
     */
    public function activityLogs(): HasMany
    {
        return $this->hasMany(ActivityLog::class);
    }

    /**
     * Orders placed by this user.
     *
     * @return HasMany<Order, $this>
     */
    public function orders(): HasMany
    {
        return $this->hasMany(Order::class);
    }

    /**
     * Saved customer shipping addresses.
     *
     * @return HasMany<CustomerAddress, $this>
     */
    public function addresses(): HasMany
    {
        return $this->hasMany(CustomerAddress::class);
    }

    /**
     * Cookie Crumbs point ledger transactions.
     *
     * @return HasMany<PointTransaction, $this>
     */
    public function pointTransactions(): HasMany
    {
        return $this->hasMany(PointTransaction::class);
    }

    /**
     * Coupon usages by this customer.
     *
     * @return HasMany<CouponUsage, $this>
     */
    public function couponUsages(): HasMany
    {
        return $this->hasMany(CouponUsage::class);
    }

    /**
     * Rupiah equivalent of points balance.
     */
    public function getPointsValueIdrAttribute(): int
    {
        return $this->points_balance * 50;
    }

    /**
     * Formatted points balance string.
     */
    public function getFormattedPointsAttribute(): string
    {
        return number_format($this->points_balance, 0, ',', '.').' Crumbs';
    }
}
